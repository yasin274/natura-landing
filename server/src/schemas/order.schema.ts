import { z } from 'zod';

/**
 * Схема оформления заказа.
 *
 * Главное решение здесь: с клиента принимаются ТОЛЬКО идентификатор товара и
 * количество. Ни цены, ни названия, ни итоговой суммы в схеме нет — всё это
 * сервер берёт из базы сам. Если бы цена приходила из браузера, любой
 * покупатель оформил бы диван за рубль, просто поправив запрос в DevTools.
 */

export const orderItemSchema = z.object({
  productId: z.uuid('Некорректный идентификатор товара'),

  /**
   * Верхняя граница не от жадности: мебель поштучно возят единицами, а
   * «999 диванов» — это либо опечатка, либо попытка сломать витрину.
   */
  quantity: z.coerce
    .number()
    .int('Количество должно быть целым')
    .min(1, 'Минимум одна штука')
    .max(20, 'Больше 20 штук одной позиции — напишите нам напрямую, посчитаем отдельно'),
});

export const createOrderSchema = z.object({
  customerName: z
    .string({ error: 'Укажите имя' })
    .trim()
    .min(2, 'Как к вам обращаться?')
    .max(100, 'Имя слишком длинное'),

  /**
   * Телефон, почта или ник — одним полем и без проверки формата.
   * Навязывать маску телефона вредно: часть покупателей оставляет Telegram,
   * а отказ формы на валидном контакте — потерянный заказ.
   */
  contact: z
    .string({ error: 'Укажите контакт' })
    .trim()
    .min(3, 'Нужен способ связи: телефон, почта или ник')
    .max(200, 'Контакт слишком длинный'),

  comment: z.string().trim().max(2000, 'Комментарий слишком длинный').optional(),

  /**
   * Согласие на обработку данных. Именно literal(true), а не boolean:
   * форма собирает имя и контакт, то есть персональные данные по 152-ФЗ,
   * и заказ без отметки согласия принимать нельзя.
   */
  consent: z.literal(true, { error: 'Без согласия на обработку данных мы не можем принять заказ' }),

  items: z
    .array(orderItemSchema)
    .min(1, 'Корзина пуста')
    .max(30, 'Слишком много разных позиций в одном заказе'),

  /**
   * Ловушка для ботов: поле спрятано в разметке, человек его не видит и не
   * заполняет, а автоматический заполнитель форм — заполняет.
   */
  honey: z.string().max(200).optional(),

  /**
   * Момент открытия формы (Date.now() на клиенте). Форма, отправленная
   * быстрее пары секунд после открытия, заполнена не руками.
   */
  openedAt: z.coerce.number().int().nonnegative().optional(),
});

export type CreateOrderInput = z.infer<typeof createOrderSchema>;
export type OrderItemInput = z.infer<typeof orderItemSchema>;
